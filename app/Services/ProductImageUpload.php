<?php
declare(strict_types=1);

namespace App\Services;

use finfo;
use InvalidArgumentException;
use RuntimeException;

final class ProductImageUpload
{
    public const MAX_BYTES = 5 * 1024 * 1024;
    private const TYPES = ['image/jpeg' => 'jpg', 'image/png' => 'png', 'image/webp' => 'webp'];

    /** @return array{tmp_name:string, extension:string}|null */
    public function validate(mixed $file): ?array
    {
        if ($file === null) {
            return null;
        }
        if (!is_array($file) || !is_int($file['error'] ?? null)) {
            throw new InvalidArgumentException('Seleccioná una sola imagen válida.');
        }
        if ($file['error'] === UPLOAD_ERR_NO_FILE) {
            return null;
        }
        if (in_array($file['error'], [UPLOAD_ERR_INI_SIZE, UPLOAD_ERR_FORM_SIZE], true)) {
            throw new InvalidArgumentException('La imagen supera el tamaño permitido. Elegí una más liviana (hasta 5 MB).');
        }
        if ($file['error'] !== UPLOAD_ERR_OK) {
            throw new InvalidArgumentException('La imagen no se subió completa. Volvé a seleccionarla e intentá otra vez.');
        }
        $temporary = $file['tmp_name'] ?? null;
        if (!is_string($temporary) || !is_uploaded_file($temporary)) {
            throw new InvalidArgumentException('No recibimos una imagen válida. Volvé a seleccionarla.');
        }
        $bytes = filesize($temporary);
        if ($bytes === false || $bytes === 0 || $bytes > self::MAX_BYTES) {
            throw new InvalidArgumentException('La imagen debe pesar entre 1 byte y 5 MB.');
        }
        $mime = (new finfo(FILEINFO_MIME_TYPE))->file($temporary);
        $dimensions = @getimagesize($temporary);
        if (!isset(self::TYPES[$mime]) || $dimensions === false || ($dimensions['mime'] ?? '') !== $mime) {
            throw new InvalidArgumentException('Usá una imagen JPG, PNG o WebP válida.');
        }
        if ($dimensions[0] < 1 || $dimensions[1] < 1 || $dimensions[0] * $dimensions[1] > 40000000) {
            throw new InvalidArgumentException('La imagen debe tener hasta 40 megapíxeles. Reducí sus dimensiones.');
        }
        return ['tmp_name' => $temporary, 'extension' => self::TYPES[$mime]];
    }

    /** @param array{tmp_name:string, extension:string} $image */
    public function save(array $image): string
    {
        $directory = $this->directory();
        if ((!is_dir($directory) && !@mkdir($directory, 0755, true)) || !is_writable($directory)) {
            throw new RuntimeException('The product image directory is not writable.');
        }
        // Match the uppercase basenames expected by product_image_by_filename().
        $filename = 'UPLOAD_' . strtoupper(bin2hex(random_bytes(16))) . '.' . $image['extension'];
        if (!@move_uploaded_file($image['tmp_name'], $directory . DIRECTORY_SEPARATOR . $filename)) {
            throw new RuntimeException('Could not move the uploaded product image.');
        }
        return $filename;
    }

    public function remove(string $filename): void
    {
        // Cleanup can only remove files generated by this uploader.
        if (preg_match('/\AUPLOAD_[A-F0-9]{32}\.(jpg|png|webp)\z/', $filename) !== 1) {
            return;
        }
        $path = $this->directory() . DIRECTORY_SEPARATOR . $filename;
        if (is_file($path) && !@unlink($path)) {
            error_log('[products] Could not clean up product image: ' . $filename);
        }
    }

    private function directory(): string
    {
        return (string)config('uploads.product_images_path', public_path('assets/images/products'));
    }
}
